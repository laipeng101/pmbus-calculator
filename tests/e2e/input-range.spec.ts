import { expect, test, type Locator, type Page } from '@playwright/test'
import { expectNoHorizontalOverflow, expectWrappedInContainer } from './helpers/layout'

const value = (page: Page) => page.locator('#value-input')
const raw = (page: Page) => page.locator('#raw-hex-input')
const result = (page: Page) => page.getByTestId('result-value')
const quantization = (page: Page) => page.getByTestId('quantization-error')

async function expectRangeError(input: Locator, error: Locator, message: RegExp) {
  await expect(input).toHaveAttribute('aria-invalid', 'true')
  await expect(input).toHaveAttribute('aria-describedby', (await error.getAttribute('id'))!)
  await expect(error).toBeVisible()
  await expect(error).toContainText(message)
}

test('HALF 真实粘贴十进制下溢保留请求，最小有限值另行量化', async ({ page, context }) => {
  await page.setViewportSize({ width: 360, height: 800 })
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('./')
  await page.getByRole('tab', { name: /HALF/ }).click()
  const input = value(page)
  const error = page.locator('#value-input-error')
  await input.fill('1')
  await expect(raw(page)).toHaveValue('3C00')
  await expect(quantization(page)).toHaveAttribute('data-kind', 'ok')

  await page.evaluate(() => navigator.clipboard.writeText('1e-400'))
  await input.press('ControlOrMeta+a')
  await input.press('ControlOrMeta+v')
  await input.press('Tab')
  await expectRangeError(input, error, /输入下溢/)
  await expect(input).toHaveValue('1e-400')
  await expect(raw(page)).toHaveValue('3C00')
  await expect(result(page)).toHaveText('1')
  await expect(quantization(page)).toHaveAttribute('data-kind', 'ok')
  await expectWrappedInContainer(error)
  await expectNoHorizontalOverflow(page)

  await page.keyboard.press('Shift+Tab')
  await expect(input).toBeFocused()
  await input.fill('-0e400')
  await expect(raw(page)).toHaveValue('8000')
  await expect(error).toHaveCount(0)
  await input.fill('5e-324')
  await expect(raw(page)).toHaveValue('0000')
  await expect(error).toHaveCount(0)
  await expect(quantization(page)).toContainText('+5e-324 (100.0000%)')
})

test('逐键输入下溢尾部与 Enter 保留最后合法 HALF 请求', async ({ page }) => {
  await page.goto('./')
  await page.getByRole('tab', { name: /HALF/ }).click()
  const input = value(page)
  const panel = quantization(page)
  await input.fill('1')
  await expect(raw(page)).toHaveValue('3C00')

  await input.press('ControlOrMeta+a')
  await input.pressSequentially('1e-32')
  await expect(raw(page)).toHaveValue('0000')
  await expect(panel).toContainText('+1e-32')
  await input.pressSequentially('4')
  await input.press('Enter')
  await expectRangeError(input, page.locator('#value-input-error'), /输入下溢/)
  await expect(input).toHaveValue('1e-324')
  await expect(raw(page)).toHaveValue('0000')
  await expect(panel).toContainText('+1e-32')
})

test('相对 LINEAR16 区分标称输入自身的下溢和电压的计算下溢', async ({ page }) => {
  await page.goto('./')
  await page.getByRole('tab', { name: /LINEAR16/ }).click()
  await raw(page).fill('0200')
  await page.getByRole('radio', { name: '相对值', exact: true }).click()
  const nominal = page.locator('#l16-nominal-vout')
  const error = page.locator('#l16-nominal-vout-error')
  await nominal.fill('5')
  await expect(result(page)).toHaveText('10')

  await nominal.fill('1e-400')
  await nominal.press('Tab')
  await expectRangeError(nominal, error, /输入下溢/)
  await expect(nominal).toHaveValue('1e-400')
  await expect(result(page)).toHaveText('10')
  await expect(page.getByRole('alert').filter({ hasText: '计算下溢' })).toHaveCount(0)

  await nominal.fill('5e-324')
  await expect(error).toHaveCount(0)
  await expect(result(page)).toHaveText('1e-323')
  await raw(page).fill('0001')
  await expect(result(page)).toHaveText('—')
  await expect(error).toHaveCount(0)
  await expect(page.getByRole('alert').filter({ hasText: '计算下溢' })).toBeVisible()
  await expect(page.getByRole('button', { name: '物理值', exact: true })).toBeDisabled()
})

test('HALF 区分十进制文本溢出和显式 Infinity', async ({ page }) => {
  await page.goto('./')
  await page.getByRole('tab', { name: /HALF/ }).click()
  const input = value(page)
  const card = page.getByTestId('half-special-semantics')
  const error = page.locator('#value-input-error')
  await input.fill('1')
  await expect(raw(page)).toHaveValue('3C00')
  await input.fill('1e400')
  await input.press('Tab')
  await expectRangeError(input, error, /数值超出可表示范围/)
  await expect(raw(page)).toHaveValue('3C00')
  await expect(card).toHaveCount(0)
  await expect(quantization(page)).toHaveAttribute('data-kind', 'ok')

  await input.fill('Infinity')
  await expect(raw(page)).toHaveValue('7C00')
  await expect(error).toHaveCount(0)
  await expect(card).toHaveAttribute('data-kind', 'half-positive-infinity')
  await expect(quantization(page)).toHaveAttribute('data-kind', 'warn')
})

test('DIRECT 360 px 范围错误实际换行，真实键盘修复后正常提交', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 })
  await page.goto('./')
  await page.getByRole('tab', { name: /DIRECT/ }).click()
  await page.getByLabel('DIRECT 系数 r').fill('-21')
  const input = value(page)
  const error = page.locator('#value-input-error')
  await input.fill('1e21')
  await input.press('Tab')
  await expect(raw(page)).toHaveValue('0001')
  await expect(result(page)).toHaveText('1e+21')
  await expect(quantization(page)).toHaveAttribute('data-kind', 'ok')

  await input.fill('-1e400')
  await input.press('Tab')
  await expectRangeError(input, error, /数值超出可表示范围/)
  await expectWrappedInContainer(error)
  await expectNoHorizontalOverflow(page)
  await expect(raw(page)).toHaveValue('0001')
  await expect(quantization(page)).toHaveAttribute('data-kind', 'ok')

  await input.click()
  await input.press('ControlOrMeta+a')
  await input.press('Backspace')
  await input.pressSequentially('2e21')
  await input.press('Enter')
  await expect(error).toHaveCount(0)
  await expect(raw(page)).toHaveValue('0002')
})

