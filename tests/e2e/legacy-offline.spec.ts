import { test, expect } from '@playwright/test'

const legacyFile = new URL('../../pmbus-calculator.html', import.meta.url)
const title = 'PMBus 数值格式计算器（离线版）'

test.use({ offline: true })

test('离线计算、命令说明和复制可直接使用', { tag: '@browser-smoke' }, async ({ page, context }) => {
  const networkRequests: string[] = []
  page.on('request', (request) => {
    if (/^https?:/.test(request.url())) networkRequests.push(request.url())
  })
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto(legacyFile.href)
  await expect(page).toHaveTitle(title)
  await expect(page.getByRole('heading', { name: title })).toBeVisible()
  await expect(page.getByRole('button', { name: '运行边界测试' })).toBeHidden()

  const raw = page.locator('#inputHex')
  const result = page.locator('#displayValue')
  const command = page.getByRole('combobox', { name: 'PMBus 命令' })
  const note = page.locator('#commandNote')
  await raw.fill('F819')
  await raw.press('Tab')
  await expect(result).toHaveText('12.5')

  await command.selectOption('STATUS_WORD')
  await expect(note).toBeVisible()
  await expect(note).toContainText('写入 0x0100 只清除 UNKNOWN 位')
  await expect(raw).toHaveValue('F819')

  await command.selectOption('READ_EIN')
  await expect(note).toContainText('PMBus Part II §18.13 描述 6 个数据字节，附录 I 表 31 列为 5 个')
  await expect(result).toHaveText('12.5')
  await raw.fill('F81A')
  await raw.press('Tab')
  await expect(result).toHaveText('13')
  await expect(note).toBeVisible()
  await expect(note).toContainText('Block Read')
  await page.locator('#copyCBtn').click()
  const macro = await page.evaluate(() => navigator.clipboard.readText())
  expect(macro).toContain('#define PMBUS_VAL  0xF81AU')
  expect(macro).not.toMatch(/READ_EIN|pmbusWrite|PEC/)

  await command.selectOption('VOUT_COMMAND')
  await expect(note).toBeHidden()
  await expect(command).toHaveValue('VOUT_COMMAND')
  await expect(raw).toHaveValue('0C00')
  await expect(result).toHaveText('12')
  await page.locator('#voutModeHex').fill('60')
  await page.locator('#voutModeHex').press('Tab')
  await expect(page.locator('#voutModeInfo')).toContainText('沿用当前 LINEAR16 指数')
  await expect(result).toHaveText('12')
  await raw.fill('0100')
  await raw.press('Tab')
  await expect(result).toHaveText('1')
  await expect(page.locator('#infoBar')).toContainText('N=-8 V=256')

  await page.getByRole('tab', { name: /IEEE.*半精度/ }).click()
  await raw.fill('7C01')
  await raw.press('Tab')
  await expect(raw).toHaveValue('7C01')
  await expect(result).toHaveText('NaN')
  const value = page.locator('#inputValue')
  await expect(value).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(value).not.toBeFocused()
  await expect(raw).toHaveValue('7C01')
  expect(networkRequests).toEqual([])
})

test('从调试面板运行边界测试后保留当前计算和命令说明', async ({ page }) => {
  await page.goto(new URL('?debug', legacyFile).href)
  const raw = page.locator('#inputHex')
  const value = page.locator('#inputValue')
  await raw.fill('F819')
  await raw.press('Tab')
  await value.fill('12.6')
  await value.press('Tab')
  await expect(page.locator('#deltaError')).toContainText('+0.100000')
  const command = page.getByRole('combobox', { name: 'PMBus 命令' })
  await command.selectOption('READ_EIN')

  await page.getByRole('button', { name: '运行边界测试' }).click()
  const output = page.locator('#debugOutput')
  await expect(output).toContainText(/\b[1-9]\d* 项通过，0 项失败/)
  await expect(output).toContainText('0x7BFF / 0x7C00 / 0x8400')
  await expect(output).toContainText('0x98/0x20/0x40/0x60/0xE0')
  await expect(raw).toHaveValue('F819')
  await expect(value).toHaveValue('12.6')
  await expect(page.locator('#deltaError')).toContainText('+0.100000')
  await expect(command).toHaveValue('READ_EIN')
  await expect(page.locator('#commandNote')).toContainText('Block Read')
})
